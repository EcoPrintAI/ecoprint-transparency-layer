/**
 * db.js — SQLite connection and schema initialisation for the Transparency layer.
 *
 * The Transparency database is intentionally separate from the SigSense
 * telemetry database (sigsense/engine/ecoprint_telemetry.db).  Identity,
 * run, and attempt records live here; raw measurements stay in SigSense.
 *
 * The schema is append-oriented: rows are inserted and their status columns
 * are updated in place, but no rows are deleted.  This makes it suitable
 * for later attribution records that need a stable history to join against.
 */

import sqlite3 from 'sqlite3';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

/**
 * Open (or create) the Transparency SQLite database.
 *
 * @param {string} [dbPath] - Absolute or relative path to the .db file.
 *   Defaults to src/transparency/transparency.db relative to this file.
 *   Pass ':memory:' for an in-memory database (useful in tests).
 * @returns {Promise<sqlite3.Database>}
 */
export function openDatabase(dbPath) {
    const resolved = dbPath ?? path.join(__dirname, 'transparency.db');
    return new Promise((resolve, reject) => {
        const db = new sqlite3.Database(resolved, (err) => {
            if (err) reject(err);
            else resolve(db);
        });
    });
}

/**
 * Initialise all Transparency tables.  Safe to call on an existing database —
 * all statements use CREATE TABLE IF NOT EXISTS.
 *
 * Tables
 * ──────
 * workloads           — stable identity for a repeatable unit of work
 * runs                — one execution of a workload
 * attempts            — one execution attempt within a run
 * context_events      — time-bounded execution context records (process, future: VM/container)
 * attribution_records — deterministic attribution of telemetry observations to workload contexts
 *
 * identity_source column (workloads / runs / attempts):
 *   'local'    — ID was generated by Transparency (UUID fallback)
 *   'external' — ID was supplied by an orchestration layer / CI system / caller
 *
 * @param {sqlite3.Database} db
 * @returns {Promise<void>}
 */
export async function initSchema(db) {
    const ddl = `
        PRAGMA journal_mode = WAL;

        CREATE TABLE IF NOT EXISTS workloads (
            workload_id        TEXT    PRIMARY KEY,
            name               TEXT    NOT NULL,
            type               TEXT    NOT NULL,
            created_at         TEXT    NOT NULL,
            parent_workload_id TEXT    REFERENCES workloads(workload_id),
            status             TEXT    NOT NULL DEFAULT 'active'
                               CHECK (status IN ('active', 'archived')),
            identity_source    TEXT    NOT NULL DEFAULT 'local'
                               CHECK (identity_source IN ('local', 'external'))
        );

        CREATE TABLE IF NOT EXISTS runs (
            run_id          TEXT PRIMARY KEY,
            workload_id     TEXT NOT NULL REFERENCES workloads(workload_id),
            started_at      TEXT NOT NULL,
            ended_at        TEXT,
            status          TEXT NOT NULL DEFAULT 'running'
                            CHECK (status IN ('running', 'completed', 'failed')),
            identity_source TEXT NOT NULL DEFAULT 'local'
                            CHECK (identity_source IN ('local', 'external'))
        );

        CREATE INDEX IF NOT EXISTS idx_runs_workload_id ON runs(workload_id);

        CREATE TABLE IF NOT EXISTS attempts (
            attempt_id      TEXT    PRIMARY KEY,
            run_id          TEXT    NOT NULL REFERENCES runs(run_id),
            workload_id     TEXT    NOT NULL REFERENCES workloads(workload_id),
            attempt_no      INTEGER NOT NULL,
            started_at      TEXT    NOT NULL,
            ended_at        TEXT,
            status          TEXT    NOT NULL DEFAULT 'running'
                            CHECK (status IN ('running', 'completed', 'failed')),
            reason          TEXT,
            identity_source TEXT    NOT NULL DEFAULT 'local'
                            CHECK (identity_source IN ('local', 'external')),
            UNIQUE (run_id, attempt_no)
        );

        CREATE INDEX IF NOT EXISTS idx_attempts_run_id      ON attempts(run_id);
        CREATE INDEX IF NOT EXISTS idx_attempts_workload_id ON attempts(workload_id);

        CREATE TABLE IF NOT EXISTS context_events (
            context_id        TEXT    PRIMARY KEY,
            workload_id       TEXT    NOT NULL,
            run_id            TEXT    NOT NULL,
            attempt_id        TEXT    NOT NULL,
            context_type      TEXT    NOT NULL DEFAULT 'process'
                              CHECK  (context_type IN ('process')),
            external_id       TEXT    NOT NULL,
            resource_id       TEXT,
            started_at        TEXT    NOT NULL,
            ended_at          TEXT,
            source            TEXT    NOT NULL,
            parent_context_id TEXT    REFERENCES context_events(context_id)
            ,process_id       INTEGER
            ,parent_process_id INTEGER
            ,executable_identity TEXT
            ,process_started_at TEXT
            ,process_start_quality TEXT
            ,provenance_classification TEXT NOT NULL DEFAULT 'unknown'
            ,provenance_source TEXT NOT NULL DEFAULT 'cli'
            ,attribution_eligible INTEGER NOT NULL DEFAULT 1
        );

        CREATE INDEX IF NOT EXISTS idx_ctx_attempt_id  ON context_events(attempt_id);
        CREATE INDEX IF NOT EXISTS idx_ctx_run_id      ON context_events(run_id);
        CREATE INDEX IF NOT EXISTS idx_ctx_workload_id ON context_events(workload_id);
        CREATE INDEX IF NOT EXISTS idx_ctx_resource_id ON context_events(resource_id);
        CREATE INDEX IF NOT EXISTS idx_ctx_started_at  ON context_events(started_at);
        CREATE INDEX IF NOT EXISTS idx_ctx_ended_at    ON context_events(ended_at);

        CREATE TABLE IF NOT EXISTS attribution_records (
            attribution_id       TEXT    PRIMARY KEY,
            telemetry_timestamp  TEXT    NOT NULL,
            workload_id          TEXT,
            run_id               TEXT,
            attempt_id           TEXT,
            context_id           TEXT,
            resource_id          TEXT,
            attributed_power_watts   REAL    NOT NULL DEFAULT 0.0,
            attributed_cpu_power_watts REAL,
            attributed_gpu_power_watts REAL,
            attributed_ane_power_watts REAL,
            attributed_client_workload_power_watts REAL,
            attributed_ecoprint_overhead_power_watts REAL,
            attributed_client_workload_carbon_gco2e REAL,
            attributed_ecoprint_overhead_carbon_gco2e REAL,
            attributed_client_workload_water_liters REAL,
            attributed_ecoprint_overhead_water_liters REAL,
            attributed_carbon_gco2e  REAL    NOT NULL DEFAULT 0.0,
            attributed_water_liters  REAL    NOT NULL DEFAULT 0.0,
            duration_seconds        REAL    NOT NULL DEFAULT 0.0,
            attribution_method   TEXT    NOT NULL,
            evidence_level       TEXT    NOT NULL
                                 CHECK (evidence_level IN ('exact', 'shared', 'unattributed')),
            attribution_version  INTEGER NOT NULL DEFAULT 1,
            created_at           TEXT    NOT NULL
        );

        CREATE INDEX IF NOT EXISTS idx_attr_attempt_id   ON attribution_records(attempt_id);
        CREATE INDEX IF NOT EXISTS idx_attr_workload_id  ON attribution_records(workload_id);
        CREATE INDEX IF NOT EXISTS idx_attr_ts           ON attribution_records(telemetry_timestamp);
        CREATE INDEX IF NOT EXISTS idx_attr_resource_id  ON attribution_records(resource_id);
        CREATE INDEX IF NOT EXISTS idx_attr_version      ON attribution_records(attribution_version);

        CREATE TABLE IF NOT EXISTS run_metrics (
            run_id                  TEXT PRIMARY KEY REFERENCES runs(run_id),
            duration_ms             REAL NOT NULL,
            average_power_watts     REAL NOT NULL,
            peak_power_watts        REAL,
            energy_wh               REAL NOT NULL,
            carbon_gco2e            REAL NOT NULL,
            water_liters            REAL NOT NULL,
            attribution_coverage    REAL NOT NULL,
            measurement_quality     TEXT NOT NULL,
            grid_intensity_quality  TEXT NOT NULL DEFAULT 'unknown',
            cpu_average_power_watts REAL,
            cpu_peak_power_watts    REAL,
            cpu_energy_wh           REAL,
            gpu_average_power_watts REAL,
            gpu_peak_power_watts    REAL,
            gpu_energy_wh           REAL,
            ane_average_power_watts REAL,
            ane_peak_power_watts    REAL,
            ane_energy_wh           REAL,
            client_workload_average_power_watts REAL,
            client_workload_peak_power_watts REAL,
            client_workload_energy_wh REAL,
            client_workload_carbon_gco2e REAL,
            client_workload_water_liters REAL,
            ecoprint_overhead_average_power_watts REAL,
            ecoprint_overhead_peak_power_watts REAL,
            ecoprint_overhead_energy_wh REAL,
            ecoprint_overhead_carbon_gco2e REAL,
            ecoprint_overhead_water_liters REAL,
            measurement_efficiency_pct REAL,
            measurement_method TEXT NOT NULL DEFAULT 'unknown',
            allocation_method TEXT NOT NULL DEFAULT 'unavailable',
            provenance_quality TEXT NOT NULL DEFAULT 'unknown',
            process_context_count INTEGER NOT NULL DEFAULT 0,
            process_lineage_coverage REAL,
            created_at              TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS experience_cases (
            experience_id             TEXT PRIMARY KEY,
            run_id                    TEXT NOT NULL UNIQUE REFERENCES runs(run_id),
            workload_id               TEXT NOT NULL REFERENCES workloads(workload_id),
            workload_name             TEXT NOT NULL,
            workload_type             TEXT NOT NULL,
            measured_facts_json       TEXT NOT NULL,
            derived_facts_json        TEXT NOT NULL,
            provenance_json           TEXT NOT NULL,
            ai_interpretation_json    TEXT,
            ai_usage_json             TEXT,
            interpretation_status    TEXT NOT NULL DEFAULT 'none'
                                      CHECK (interpretation_status IN ('none', 'unverified', 'low-confidence')),
            interpretation_confidence REAL,
            outcome_json              TEXT,
            outcome_status            TEXT NOT NULL DEFAULT 'none'
                                      CHECK (outcome_status IN ('none', 'unverified', 'verified')),
            created_at                TEXT NOT NULL
        );
        CREATE INDEX IF NOT EXISTS idx_experience_workload_type ON experience_cases(workload_type);
        CREATE INDEX IF NOT EXISTS idx_experience_created_at ON experience_cases(created_at);
    `;

    await new Promise((resolve, reject) => {
        db.exec(ddl, (err) => {
            if (err) reject(err);
            else resolve();
        });
    });

    // Additive migrations: add columns to tables created before they existed.
    // SQLite does not support ADD COLUMN IF NOT EXISTS, so we attempt each
    // ALTER and silently swallow the "duplicate column name" error.
    await _addColumnIfMissing(db, 'workloads', 'identity_source', "TEXT NOT NULL DEFAULT 'local'");
    await _addColumnIfMissing(db, 'runs',      'identity_source', "TEXT NOT NULL DEFAULT 'local'");
    await _addColumnIfMissing(db, 'attempts',  'identity_source', "TEXT NOT NULL DEFAULT 'local'");
    await _addColumnIfMissing(db, 'attribution_records', 'duration_seconds', 'REAL NOT NULL DEFAULT 0.0');
    for (const name of [
        'attributed_client_workload_power_watts', 'attributed_ecoprint_overhead_power_watts',
        'attributed_client_workload_carbon_gco2e', 'attributed_ecoprint_overhead_carbon_gco2e',
        'attributed_client_workload_water_liters', 'attributed_ecoprint_overhead_water_liters',
    ]) await _addColumnIfMissing(db, 'attribution_records', name, 'REAL');
    for (const [name, type] of [
        ['process_id', 'INTEGER'], ['parent_process_id', 'INTEGER'], ['executable_identity', 'TEXT'],
        ['process_started_at', 'TEXT'], ['process_start_quality', 'TEXT'],
        ['provenance_classification', "TEXT NOT NULL DEFAULT 'unknown'"],
        ['provenance_source', "TEXT NOT NULL DEFAULT 'cli'"],
        ['attribution_eligible', 'INTEGER NOT NULL DEFAULT 1'],
    ]) await _addColumnIfMissing(db, 'context_events', name, type);
    for (const [name, type] of [
        ['client_workload_average_power_watts', 'REAL'], ['client_workload_peak_power_watts', 'REAL'],
        ['client_workload_energy_wh', 'REAL'], ['client_workload_carbon_gco2e', 'REAL'], ['client_workload_water_liters', 'REAL'],
        ['ecoprint_overhead_average_power_watts', 'REAL'], ['ecoprint_overhead_peak_power_watts', 'REAL'],
        ['ecoprint_overhead_energy_wh', 'REAL'], ['ecoprint_overhead_carbon_gco2e', 'REAL'], ['ecoprint_overhead_water_liters', 'REAL'],
        ['measurement_efficiency_pct', 'REAL'], ['measurement_method', "TEXT NOT NULL DEFAULT 'unknown'"],
        ['allocation_method', "TEXT NOT NULL DEFAULT 'unavailable'"], ['provenance_quality', "TEXT NOT NULL DEFAULT 'unknown'"],
        ['process_context_count', 'INTEGER NOT NULL DEFAULT 0'], ['process_lineage_coverage', 'REAL'],
    ]) await _addColumnIfMissing(db, 'run_metrics', name, type);
    for (const component of ['cpu', 'gpu', 'ane']) {
        await _addColumnIfMissing(db, 'attribution_records', `attributed_${component}_power_watts`, 'REAL');
        await _addColumnIfMissing(db, 'run_metrics', `${component}_average_power_watts`, 'REAL');
        await _addColumnIfMissing(db, 'run_metrics', `${component}_peak_power_watts`, 'REAL');
        await _addColumnIfMissing(db, 'run_metrics', `${component}_energy_wh`, 'REAL');
    }
    await _addColumnIfMissing(db, 'run_metrics', 'grid_intensity_quality', "TEXT NOT NULL DEFAULT 'unknown'");
    await _addColumnIfMissing(db, 'experience_cases', 'ai_usage_json', 'TEXT');
}

/**
 * Attempt to add a column; silently ignore the error when the column already
 * exists (SQLite error message contains "duplicate column name").
 *
 * @param {sqlite3.Database} db
 * @param {string} table
 * @param {string} column
 * @param {string} definition  SQL type + constraints fragment
 * @returns {Promise<void>}
 */
function _addColumnIfMissing(db, table, column, definition) {
    return new Promise((resolve) => {
        db.run(`ALTER TABLE ${table} ADD COLUMN ${column} ${definition}`, (err) => {
            // Ignore "duplicate column name" — the column already exists from
            // the CREATE TABLE statement, which is the normal case.
            if (err && !err.message.includes('duplicate column name')) {
                // Unexpected error — log but don't crash schema init.
                console.warn(`[TRANSPARENCY] Migration warning (${table}.${column}): ${err.message}`);
            }
            resolve();
        });
    });
}

// ── Thin promise wrappers around the callback-style sqlite3 API ─────────────

/** @param {sqlite3.Database} db @param {string} sql @param {any[]} params */
export function dbRun(db, sql, params = []) {
    return new Promise((resolve, reject) => {
        db.run(sql, params, function (err) {
            if (err) reject(err);
            else resolve(this); // 'this' carries lastID / changes
        });
    });
}

/** @param {sqlite3.Database} db @param {string} sql @param {any[]} params */
export function dbGet(db, sql, params = []) {
    return new Promise((resolve, reject) => {
        db.get(sql, params, (err, row) => {
            if (err) reject(err);
            else resolve(row ?? null);
        });
    });
}

/** @param {sqlite3.Database} db @param {string} sql @param {any[]} params */
export function dbAll(db, sql, params = []) {
    return new Promise((resolve, reject) => {
        db.all(sql, params, (err, rows) => {
            if (err) reject(err);
            else resolve(rows);
        });
    });
}

/** Close the database connection. */
export function closeDatabase(db) {
    return new Promise((resolve, reject) => {
        db.close((err) => {
            if (err) reject(err);
            else resolve();
        });
    });
}
